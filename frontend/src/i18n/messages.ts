const PSEUDO_MAP: Record<string, string> = {
  a: 'á', b: 'ƀ', c: 'ç', d: 'đ', e: 'ë', f: 'ƒ', g: 'ğ', h: 'ħ', i: 'ï', j: 'ĵ', k: 'ķ', l: 'ľ', m: 'ɱ',
  n: 'ñ', o: 'ô', p: 'þ', q: 'ʠ', r: 'ř', s: 'š', t: 'ţ', u: 'ü', v: 'ṽ', w: 'ŵ', x: 'ẋ', y: 'ÿ', z: 'ž',
};

function pseudoSegment(value: string): string {
  const musicalTokens: string[] = [];
  const protectedValue = value.replace(/\b[A-G](?:#|b|♯|♭)?\b/g, (token) => `\uE000${musicalTokens.push(token) - 1}\uE001`);
  const expanded = [...protectedValue].map((character) => {
    const lower = character.toLowerCase();
    const mapped = PSEUDO_MAP[lower];
    if (!mapped) return character;
    return character === lower ? mapped : mapped.toUpperCase();
  }).join('');
  return expanded.replace(/\uE000(\d+)\uE001/g, (_match, index) => musicalTokens[Number(index)]);
}

export function pseudoLocalizeMessage(value: string): string {
  let output = '［';
  let segment = '';
  let braceDepth = 0;
  for (const character of value) {
    if (character === '{') {
      if (braceDepth === 0) {
        output += pseudoSegment(segment);
        segment = '';
      }
      braceDepth += 1;
      output += character;
    } else if (character === '}') {
      output += character;
      braceDepth = Math.max(0, braceDepth - 1);
    } else if (braceDepth > 0) {
      output += character;
    } else {
      segment += character;
    }
  }
  output += pseudoSegment(segment);
  return `${output}］`;
}

export function messagesForLocale(locale: string): MessageCatalog {
  if (locale === 'en-XA') {
    return Object.fromEntries(Object.entries(englishMessages).map(([id, value]) => [id, pseudoLocalizeMessage(value)])) as MessageCatalog;
  }
  return { ...englishMessages, ...(localeMessageOverrides[locale] ?? {}) };
}
